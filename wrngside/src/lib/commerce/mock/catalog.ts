const S = (label: string, stock: number): RawSize => ({ label, available: stock > 0, stock });
/** Stock for S, M, L, XL, XXL. */
const sizes = (s: number, m: number, l: number, xl: number, xxl: number) => [S("S", s), S("M", m), S("L", l), S("XL", xl), S("XXL", xxl)];

function media(handle: string, colour: string, views: [file: string, label: string][] = []): RawImages {
  const base = `/products/${handle}/${colour}`;
  return {
    cutout: `${base}/cutout.webp`,
    cutoutBack: `${base}/cutout-back.webp`,
    front: `${base}/front.webp`,
    back: `${base}/back.webp`,
    views: views.map(([file, label]) => ({ src: `${base}/${file}.webp`, label })),
    model: [`${base}/model-1.webp`],
  };
}


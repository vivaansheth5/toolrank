/**
 * Mock catalogue in the brief's raw shape. `lib/commerce` reshapes it into
 * Storefront-API-like objects; scripts/ read it too, so this file must stay
 * import-free.
 *
 * Every piece is a real WRNGSIDE article. Names come from the prints; prices,
 * stock, GSM, fabric and fit notes are placeholders until the line sheet
 * lands (see README → Before launch).
 *
 * Images live in /products/{handle}/{colour}/ (cutout.webp and
 * cutout-back.webp are on transparent, the rest are 4:5 shots on dust). Swap
 * the files for the original photography and keep the names.
 */

export type Category = "tees" | "jerseys" | "outerwear" | "bottoms";
export type HangStyle = "pegs" | "hanger";
export type GarmentKind = "tee" | "tank" | "layered" | "jersey" | "longjersey" | "polo" | "hoodie" | "jacket" | "sweatpants";
export type SizeChartKey = "tee" | "tank" | "jersey" | "longsleeve" | "hoodie" | "jacket" | "sweatpants";

export interface RawView {
  src: string;
  /** Finishes the alt text: "BAROQUE sweatpants in Black, left side". */
  label: string;
}

export interface RawImages {
  /** Front and back views on transparent: THE LINE hangs the `lead` side. */
  cutout: string;
  cutoutBack: string;
  front: string;
  back: string;
  /** Extra angles and close-ups, shown after the back. */
  views: RawView[];
  /** The piece hanging on the wire at night. */
  model: string[];
}

export interface RawColour {
  name: string;
  slug: string;
  hex: string;
  media: RawImages;
}

export interface RawSize {
  label: string;
  available: boolean;
  stock: number;
}

/**
 * Where the piece is held on THE LINE, measured off its cutout: peg (or
 * hanger shoulder) positions as fractions of the width, and how far below
 * the top of the cutout that grip sits, in cm.
 */
export interface RawHold {
  pegs: number[];
  dropCm: number;
}

export interface RawProduct {
  id: string;
  handle: string;
  title: string;
  /** e.g. "oversized tee" — used in accessible names: "BLACK HOLE oversized tee". */
  type: string;
  category: Category;
  kind: GarmentKind;
  price: number;
  compareAtPrice?: number;
  currency: "INR";
  colours: RawColour[];
  sizes: RawSize[];
  gsm: number;
  fit: string;
  fabric: string;
  care: string[];
  hangStyle: HangStyle;
  /** 0–1. Heavier pieces sag the cable more and swing less, more slowly. */
  weight: number;
  drop: string;
  isNew: boolean;
  isLimited: boolean;
  restocking?: boolean;
  /** Locked until this time (ISO, IST offset). */
  releaseAt?: string;
  description: string;
  details: string[];
  sizeChart: SizeChartKey;
  /** Real-world size of the cutout in cm (sets true relative scale on THE LINE). */
  dims: { w: number; h: number };
  hold: RawHold;
  /** The side listings, THE LINE and the gallery lead with: "back" when that's where the print is. */
  lead?: "front" | "back";
  tags: string[];
}


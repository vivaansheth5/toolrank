import type { CategorySlug } from "./types";

/**
 * Category-aware comparison dimension schema. Each dimension is a
 * deterministic classifier definition, not hand-authored per-tool content —
 * lib/comparisonProfile.ts scans every tool's own real fields (name,
 * tagline, description, subcategory, tags, features, pros, cons) for these
 * keyword fragments and only ever reports what it actually finds there.
 *
 * Extensible by design: adding a new dimension or category here is the only
 * change needed — nothing about ChatGPT/Claude (or any other tool) is
 * hardcoded into the matching logic itself.
 */
export interface ComparisonDimension {
  id: string;
  label: string;
  emoji: string;
  /** Substrings that count as a confident ("strong"/"good") signal. */
  strongKeywords: string[];
  /** Weaker/adjacent substrings — a hit here alone yields "basic"/"limited". */
  goodKeywords?: string[];
  /** lib/needSignals.ts chip ids whose presence in a ParsedNeed makes this
   *  dimension worth surfacing in a personalized comparison. */
  relatedChipIds: string[];
  /** One sentence explaining why this axis matters when deciding. */
  whyItMatters: string;
  /** A short real-world task phrase this dimension maps to — powers the
   *  scenario-comparison section (lib/comparisonNarrative.ts) so tools are
   *  compared against what the user will actually DO, not just an abstract
   *  capability label. */
  scenario: string;
}

